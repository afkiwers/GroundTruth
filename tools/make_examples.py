"""Build the example boards in examples/ (checked in): small KiCad projects that show one feature each, ready to open
in KiCad and simulate with GroundTruth (each has its settings file in its groundtruth/ folder).

    .venv/Scripts/python tools/make_examples.py              # writes examples/
    .venv/Scripts/python tools/make_examples.py --out DIR    # somewhere else

The boards come from the test suite's generator (tests/boardgen.py), the same ones the tests simulate. KiCad's own
CLI fills the zones and saves each board in KiCad 10's format. Run it again after changing a generator.
"""
from __future__ import annotations

import argparse
import os
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
sys.path.insert(0, str(ROOT / "tests"))

INDEX = """# GroundTruth examples

Small 2-layer boards (50 x 20 mm, a GND plane on B.Cu), one feature each. Open a folder's `.kicad_pro` in KiCad 10,
open its PCB editor and start GroundTruth: the settings file in its `groundtruth/` folder already lists the signal
net, its source and load, and the part models. Or from the command line:

    groundtruth simulate examples/opamp_path/opamp_path.kicad_pcb --format html --out-dir out/

| Folder | Shows |
|---|---|
{rows}
| `gitlab-ci.yml` | A GitLab pipeline: the checks on every merge request, the simulation with its HTML report on main ([CI guide](../docs/guide/ci.md)). |
| `release.gtthresholds.yaml` | The documented thresholds template for `groundtruth verify` (the CI release gate in `gitlab-ci.yml`): every criterion, edit the limits. |

The boards are made by `tools/make_examples.py` from `tests/boardgen.py` (the boards the tests simulate); the files
here are regenerated by it, so edit the generator rather than the boards. `gitlab-ci.yml` (a GitLab pipeline running
the checks and the simulation in CI) and `release.gtthresholds.yaml` (`groundtruth verify --write-template` writes the
same) are kept as they are.
"""


def _examples():
    """The examples: (folder name, description for the README, board generator, net, part models)."""
    from boardgen import opamp_path_board, series_path_board
    from groundtruth.components.models import ComponentModel
    from groundtruth.config.settings import NetSpec
    inductor = {"L1": ComponentModel("inductor", {"L": 1e-6, "R": 0.1})}
    net = NetSpec("SIG_A", "U1.1", ["U2.1"], 20e6, 1e-9, signal_class="example clock")
    return [
        ("opamp_path", "A signal path through an op-amp stage: U1 → 33 Ω R1 → op-amp U5 (Gain 10, GBW 10 MHz from its "
         "symbol fields) → U2. Two current loops, both returning at U5's GND pin; the report's signal path lists "
         "the op-amp with its gain at the worst harmonic.",
         opamp_path_board(Gain="10", GBW="10MHz"), net, {}),
        ("series_path", "A signal path across four nets: U1 → 33 Ω R1 → 1 µH L1 → 100 nF C1 (an AC-coupling capacitor, "
         "named in the net's Pass through) → U2. Each part's impedance counts at its place; the inductor resonates "
         "with the load near 60 MHz and blocks the current above.",
         series_path_board(), _with(net, through=["C1"]), inductor),
        ("rc_filter", "The series path with a 1 nF capacitor C9 from SIG_B to GND after R1: an RC low-pass. Above its "
         "corner (~5 MHz) the current returns through C9: a current loop of its own, shorter than the whole path.",
         series_path_board(("C9", "1n", "C", 20.0, "SIG_B")), _with(net, through=["C1"]), inductor),
        ("termination", "The series path with a 50 Ω resistor R9 from SIG_D to GND just beyond the receiver: a "
         "parallel termination as a part. It gives what `load_ohms: 50` on the net gives (within 0.5 dB).",
         series_path_board(("R9", "50", "R", 46.5, "SIG_D")), _with(net, through=["C1"]), inductor),
    ]


def _with(spec, **kw):
    """A copy of a dataclass spec with some fields changed."""
    from dataclasses import replace
    return replace(spec, **kw)


def _project(d: Path, name: str, gen, net, models: dict, text: str) -> None:
    """Write one example project into d: the board, a minimal .kicad_pro, zones filled by kicad-cli when installed,
    and its settings file (the net and part models) and a README.txt with the description."""
    from groundtruth.adapters.file_source import load_board
    from groundtruth.config.settings import SettingsFile, settings_path
    d.mkdir(parents=True, exist_ok=True)
    pcb = gen.write(d / f"{name}.kicad_pcb")
    (d / f"{name}.kicad_pro").write_text(f'{{\n  "meta": {{\n    "filename": "{name}.kicad_pro",\n    "version": 3\n'
                                         '  }\n}\n', encoding="utf-8")
    cli = shutil.which("kicad-cli") or os.path.join(os.environ.get("ProgramFiles", ""), "KiCad", "10.0", "bin",
                                                     "kicad-cli.exe")
    if os.path.exists(cli):         # KiCad fills the zones and writes the board in its own format
        rpt = d / "drc.rpt"
        r = subprocess.run([cli, "pcb", "drc", "--refill-zones", "--save-board", "-o", str(rpt), str(pcb)],
                           capture_output=True, text=True)
        rpt.unlink(missing_ok=True)
        (d / f"{name}.kicad_prl").unlink(missing_ok=True)
        print(f"{name}: kicad-cli refill", "ok" if r.returncode in (0, 5) else r.stderr.strip()[-300:])
    else:
        print(f"{name}: kicad-cli not found: the zones stay unfilled (press B in KiCad)", file=sys.stderr)
    board = load_board(pcb)
    settings = settings_path(pcb)
    settings.unlink(missing_ok=True)
    sc = SettingsFile.new(settings, board)
    sc.set_nets([net])
    for ref, model in models.items():
        sc.set_component(ref, model)
    sc.save()
    SettingsFile.load(settings).config            # loads cleanly
    (d / "README.txt").write_text(f"{name}\n{'=' * len(name)}\n\n{text}\n", encoding="utf-8")


def main() -> int:
    """Write every example project and examples/README.md listing them, then print the files written."""
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--out", type=Path, default=ROOT / "examples")
    args = ap.parse_args()
    rows = []
    for name, text, gen, net, models in _examples():
        _project(args.out / name, name, gen, net, models, text)
        rows.append(f"| `{name}/` | {text} |")
    (args.out / "README.md").write_text(INDEX.format(rows="\n".join(rows)), encoding="utf-8")
    for p in sorted(args.out.rglob("*")):
        if p.is_file():
            print(f"  {p.relative_to(args.out)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
